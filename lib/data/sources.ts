export type SourceStatus = "live" | "fallback" | "planned" | "paid-only";
export type SourceAuth = "none" | "ua-only" | "key" | "oauth";
export type SourceSustain =
  | "stable" // generous quota, no recent breakage
  | "tightened" // recently tightened (key required, lower quota)
  | "fragile" // unofficial / scraped / liable to break
  | "deprecated"; // retired or planned-retire

export type SourceCategory =
  | "us-equities"
  | "id-equities"
  | "global-macro"
  | "news-sentiment"
  | "alt-data"
  | "academic"
  | "infra";

export interface SourceRecord {
  id: string;
  name: string;
  url: string;
  category: SourceCategory;
  region: "US" | "ID" | "GLOBAL";
  auth: SourceAuth;
  freeTier: string;
  sustainability: SourceSustain;
  useCases: string;
  status: SourceStatus;
  edgeRank: 1 | 2 | 3; // 1 = primary edge, 2 = workhorse, 3 = commodity
  tosNote?: string;
  wrapper?: string;
  citationId?: string; // links to citations.ts
}

